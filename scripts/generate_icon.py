"""Generate Orbe's raster icons from the same geometry as packages/brand/mark.svg."""
from pathlib import Path
from shutil import copyfile
from PIL import Image, ImageDraw, PngImagePlugin

ROOT = Path(__file__).resolve().parents[1]
SCALE = 16
image = Image.new('RGBA', (64 * SCALE, 64 * SCALE))
draw = ImageDraw.Draw(image)
accent = '#ff647e'

def curve(points, color, width):
    sampled = []
    for index in range(201):
        t = index / 200
        weights = ((1-t)**3, 3*(1-t)**2*t, 3*(1-t)*t*t, t**3)
        sampled.append(tuple(sum(weights[i] * points[i][axis] for i in range(4)) * SCALE for axis in range(2)))
    draw.line(sampled, fill=color, width=round(width*SCALE), joint='curve')
    radius = width*SCALE/2
    for x, y in (sampled[0], sampled[-1]):
        draw.ellipse((x-radius, y-radius, x+radius, y+radius), fill=color)

draw.ellipse(tuple(v*SCALE for v in (7.5, 7.5, 56.5, 56.5)), outline=accent, width=7*SCALE)
curve([(12,44),(17,46),(28,43),(38,36)], (0,0,0,0), 10)
curve([(38,36),(48,29),(55,22),(54,17)], (0,0,0,0), 10)
curve([(10,42),(14,46),(27,42),(39,34)], accent, 5)
curve([(39,34),(51,26),(58,17),(54,13)], accent, 5)

icon = image.resize((512,512), Image.Resampling.LANCZOS)
metadata = PngImagePlugin.PngInfo()
metadata.add_text('orbe-origin', 'Original code-native Orbe mark. Master: packages/brand/mark.svg. Generated by scripts/generate_icon.py.')
icon.save(ROOT / 'src/renderer/assets/orbe.png', pnginfo=metadata)
icon.save(ROOT / 'resources/icon.png', pnginfo=metadata)
icon.save(ROOT / 'resources/icon.ico', format='ICO', sizes=[(16,16),(24,24),(32,32),(48,48),(64,64),(128,128),(256,256)])
copyfile(ROOT / 'packages/brand/mark.svg', ROOT / 'resources/orbe.svg')
public = ROOT / 'apps/web/public'
public.mkdir(parents=True, exist_ok=True)
copyfile(ROOT / 'packages/brand/mark.svg', public / 'favicon.svg')
print('Generated Orbe SVG, PNG and Windows icon.')
